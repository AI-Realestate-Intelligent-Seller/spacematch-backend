def now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def uid():
    return str(uuid4())


def pg_enabled() -> bool:
    return bool(DATABASE_URL)


# ------------------------------------------------------------- Postgres ----

_NAMED = re.compile(r"(?<![:\w]):([A-Za-z_]\w*)")
_pool = None
_pool_url = None
_pool_lock = threading.Lock()


def _pg_sql(sql: str, params) -> str:
    if isinstance(params, dict):
        return _NAMED.sub(r"%(\1)s", sql)
    return sql.replace("?", "%s") if params else sql


def _get_pool():
    global _pool, _pool_url
    with _pool_lock:
        if _pool is None or _pool_url != DATABASE_URL:
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool
            if _pool is not None:
                _pool.close()
            # autocommit: single reads cost one round trip; db() wraps writes in an explicit transaction.
            # prepare_threshold=None: no server-side prepared statements (safe behind Supabase's pooler).
            _pool = ConnectionPool(DATABASE_URL, min_size=1, max_size=DATABASE_POOL_MAX, timeout=20, open=True,
                                   kwargs={"row_factory": dict_row, "prepare_threshold": None, "autocommit": True},
                                   name="spacematch")
            _pool_url = DATABASE_URL
        return _pool


def close_pool():
    global _pool, _pool_url
    with _pool_lock:
        if _pool is not None:
            _pool.close()
        _pool = _pool_url = None


class _PgConn:
    """sqlite3-like facade over a psycopg connection: execute(sql, params) with ? / :name placeholders."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params=()):
        if DATABASE_LOGGING:
            log.info("SQL %s | %s", " ".join(sql.split())[:300], params)
        return self._conn.execute(_pg_sql(sql, params), params or None)

    def executescript(self, sql: str):
        self._conn.execute(sql)  # several statements, no parameters


# --------------------------------------------------------------- facade ----

@contextmanager
def db():
    """One transaction: committed on success, rolled back on error."""
    if pg_enabled():
        with _get_pool().connection() as conn, conn.transaction():  # BEGIN ... COMMIT / ROLLBACK
            yield _PgConn(conn)
        return
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH, timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys=ON")
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


@contextmanager
def _reader():
    """A connection for a single read: no transaction round trips on Postgres."""
    if pg_enabled():
        with _get_pool().connection() as conn:
            yield _PgConn(conn)
    else:
        with db() as c:
            yield c


def get_one(sql: str, params=()):
    with _reader() as c:
        row = c.execute(sql, params).fetchone()
        return dict(row) if row else None


def get_many(sql: str, params=()):
    with _reader() as c:
        return [dict(r) for r in c.execute(sql, params).fetchall()]


def _ddl(sql: str) -> str:
    """Schema text shared by both backends; {ROWID} / {NOCASE} differ."""
    if pg_enabled():
        return sql.replace("{ROWID}", "rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,").replace("{NOCASE}", "")
    return sql.replace("{ROWID}", "").replace("{NOCASE}", " COLLATE NOCASE")


def _columns(c, table: str) -> set[str]:
    if pg_enabled():
        rows = c.execute("SELECT column_name AS name FROM information_schema.columns "
                         "WHERE table_schema=current_schema() AND table_name=?", (table,)).fetchall()
    else:
        rows = c.execute(f"PRAGMA table_info({table})").fetchall()
    return {r["name"] for r in rows}


REELS_PLATFORMS_SQL = "CHECK(platform IN ('instagram','facebook','youtube','tiktok'))"


def _allow_new_platforms():
    """SQLite v0.4: older databases only allow instagram/facebook reels. Rebuild the
    reels table with the wider CHECK, keeping every row, link and snapshot."""
    conn = sqlite3.connect(DB_PATH, timeout=10)
    try:
        row = conn.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name='reels'").fetchone()
        if not row or "'youtube'" in row[0]:
            return
        conn.execute("PRAGMA foreign_keys=OFF")  # don't cascade-delete links/snapshots
        new_sql = row[0].replace("CREATE TABLE reels", "CREATE TABLE reels_new", 1).replace(
            "CHECK(platform IN ('instagram','facebook'))", REELS_PLATFORMS_SQL)
        with conn:
            conn.execute(new_sql)
            conn.execute("INSERT INTO reels_new SELECT * FROM reels")
            conn.execute("DROP TABLE reels")
            conn.execute("ALTER TABLE reels_new RENAME TO reels")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_reels_account ON reels(account_id)")
    finally:
        conn.close()


