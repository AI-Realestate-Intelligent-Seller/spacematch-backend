"""Storage: users, properties, broker access, reels (social links), snapshots, refreshes and logs.

Two backends behind one small interface (`db()`, `get_one()`, `get_many()`):
  - Postgres (e.g. Supabase) when DATABASE_URL is set - pooled psycopg 3 connections.
  - SQLite at DB_PATH otherwise (local development and the test suite).
SQL is written once with `?` / `:name` placeholders and translated for Postgres. Postgres tables
that need a stable insertion order get an identity column named `rowid`, matching SQLite's.
"""
